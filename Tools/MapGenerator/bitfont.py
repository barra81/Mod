def text_width(text, scale=1):
    return len(text) * 6 * scale


def draw_text(img, x, y, text, col, scale=1):
    """Draw text (upper-cased) into img (rows of (r, g, b)) with its top left corner at (x, y)."""
    for n, ch in enumerate(text.upper()):
        rows = GLYPHS.get(ch, GLYPHS[' ']).split()
        for ry, row in enumerate(rows):
            for rx, bit in enumerate(row):
                if bit != '1':
                    continue
                for dy in range(scale):
                    for dx in range(scale):
                        px, py = x + (n * 6 + rx) * scale + dx, y + ry * scale + dy
                        if 0 <= py < len(img) and 0 <= px < len(img[py]):
                            img[py][px] = col
